// using for and while loop to print numbers from 1 to 100
public class _04Practice {
    public static void main(String[] args) {
       int  i = 1;
        while (i <= 100) {
            System.out.print(i + " ");
            i++;
        }
        System.out.println();
        for (int j = 1; j <= 100; j++) {
            System.out.print(j + " ");
        }
    }
}
